#!/usr/bin/env bash
# Regenerates the contract ABIs from mergit-contracts. Never edit the outputs by hand (HLD Pr7).
#   chain/abi/<Name>.json        read by the Rust chain client (alloy sol! macro)
#   frontend/src/chain/abi.ts     read by the web app (viem, wagmi)
# The ABIs come from the interfaces in mergit-contracts/src/interfaces, which declare every external
# function, event and custom error a client needs.
# Usage: chain/abi/sync.sh [path-to-mergit-contracts]   (default: ../mergit-contracts next to this repo)
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
contracts="$(cd "${1:-$repo/../mergit-contracts}" && pwd)"
(cd "$contracts" && forge build --silent)
python3 - "$contracts/out" "$here" "$repo/frontend/src/chain/abi.ts" <<'PY'
import json, sys, pathlib
out, abi_dir, ts_path = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3])
names = ["Identity", "ReceiptRegistry", "Escrow", "StakeVault", "ChallengeManager", "ReputationAnchor"]
ts = ["// Generated by chain/abi/sync.sh from mergit-contracts. Do not edit.", ""]
for n in names:
    abi = json.loads((out / f"I{n}.sol" / f"I{n}.json").read_text())["abi"]
    (abi_dir / f"{n}.json").write_text(json.dumps(abi, indent=2) + "\n")
    var = n[0].lower() + n[1:] + "Abi"
    ts.append(f"export const {var} = {json.dumps(abi, indent=2)} as const;\n")
ts_path.parent.mkdir(parents=True, exist_ok=True)
ts_path.write_text("\n".join(ts))
print(f"wrote {len(names)} ABIs to {abi_dir} and {ts_path}")
PY
